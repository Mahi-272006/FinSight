import { Panel } from './ui.jsx'
import './ResearchResultPanels.css'

// The validation badge is shared by the result panels and the Research
// page's session run list. It is a component (not a plain function) so this
// file stays component-only for fast refresh.
export function ValidationBadge({ validation }) {
  if (!validation) {
    return <span className="research-validation research-validation--none">Not validated</span>
  }
  return (
    <span className={`research-validation research-validation--${validation.ok ? 'pass' : 'fail'}`}>
      {validation.ok ? 'PASS' : 'FAIL'}
    </span>
  )
}

function formatToolArgs(args) {
  const entries = Object.entries(args)
  if (entries.length === 0) return 'No parameters'
  return entries.map(([key, value]) => `${key}: ${String(value)}`).join(' · ')
}

// Empty buckets stay hidden; the verdict line above never does, so a failed
// validation is always visible even when every detail bucket is empty.
function Bucket({ label, items }) {
  if (!items || items.length === 0) return null
  return (
    <div className="research-bucket">
      <p className="research-bucket__label">{label}</p>
      <ul className="research-bucket__list">
        {items.map((item, index) => <li key={`${label}-${index}`}>{item}</li>)}
      </ul>
    </div>
  )
}

// The stored ResearchResult body is byte-identical for a live run and a
// saved report: answer, deterministic validation, retrieved-tool audit and
// the recorded removals. Save metadata lives outside that body (the /research
// response adds it; a report's copy sits at the detail response's top level),
// so the page supplies the save line as a string instead.
export function ResearchResultPanels({ result, saveLine }) {
  const validation = result.validation
  const bucketsEmpty = !validation
    || (!validation.verified_numbers?.length
      && !validation.unverified_numbers?.length
      && !validation.unsupported_citations?.length
      && !validation.notes?.length)

  return (
    <>
      <Panel
        eyebrow="ANSWER"
        title="Evidence-validated answer"
        className="research-answer-panel"
        action={(
          <span
            className="research-source"
            title="The answer text is generated by the LLM, then filtered by the deterministic evidence validator."
          >
            LLM-generated · evidence-validated
          </span>
        )}
      >
        <p className="research-answer__meta">{result.ticker} · {result.company.name}</p>
        <p className="research-answer__question">{result.question}</p>
        <p className="research-answer__text">{result.final_answer}</p>
        <p className="research-save-status">{saveLine}</p>
      </Panel>

      <Panel
        eyebrow="EVIDENCE CHECK"
        title="Deterministic validation"
        className="research-validation-panel"
        action={<ValidationBadge validation={validation} />}
      >
        {validation ? (
          <>
            <p className={`research-verdict research-verdict--${validation.ok ? 'pass' : 'fail'}`}>
              {validation.ok
                ? 'PASS — every citation in the answer is supported by retrieved evidence and every figure was verified.'
                : 'FAIL — the answer could not be fully verified against retrieved evidence. See the checks below for what failed.'}
            </p>
            <div className="research-buckets">
              <Bucket label="Verified numbers" items={validation.verified_numbers} />
              <Bucket label="Unverified numbers" items={validation.unverified_numbers} />
              <Bucket label="Unsupported citations" items={validation.unsupported_citations} />
              <Bucket label="Notes" items={validation.notes} />
            </div>
            {bucketsEmpty && (
              <p className="research-note">
                No unverified figures, unsupported citations, or validation notes were recorded.
              </p>
            )}
          </>
        ) : (
          <p className="research-note">The backend returned no validation report for this run.</p>
        )}
      </Panel>

      <Panel eyebrow="CITATIONS" title="Accessions cited in the answer" className="research-citations-panel">
        {result.citations.length === 0 ? (
          <p className="research-note">No accession numbers appear in the final answer.</p>
        ) : (
          <ul className="research-citations">
            {result.citations.map((accession) => <li key={accession}>{accession}</li>)}
          </ul>
        )}
      </Panel>

      <Panel eyebrow="EVIDENCE RETRIEVED" title="Tool calls this run" className="research-tools-panel">
        {result.tool_calls.length === 0 ? (
          <p className="research-note">No tools were called for this run.</p>
        ) : (
          <ol className="research-tools">
            {result.tool_calls.map((call, index) => (
              <li className="research-tool" key={`${call.tool}-${index}`}>
                <span className="research-tool__name">{call.tool}</span>
                <span className="research-tool__args">{formatToolArgs(call.args)}</span>
                {call.chunk_ids.length > 0 && (
                  <span className="research-tool__chunks">Filing chunks: {call.chunk_ids.join(', ')}</span>
                )}
              </li>
            ))}
          </ol>
        )}
      </Panel>

      <Panel eyebrow="LIMITATIONS" title="What this answer omits" className="research-limitations-panel">
        <p className="research-note">
          Sentences the validator removed from the draft, with the reason the backend recorded.
        </p>
        {result.limitations.length === 0 ? (
          <p className="research-note">Nothing was removed from the draft for this run.</p>
        ) : (
          <ul className="research-limitations">
            {result.limitations.map((item, index) => <li key={`limitation-${index}`}>{item}</li>)}
          </ul>
        )}
      </Panel>

      <Panel eyebrow="AUDIT" title="Run trace" className="research-audit-panel">
        <details className="research-audit">
          <summary>
            Show the audit trace — {result.iterations} iteration(s), {result.revises} revision(s)
          </summary>
          <ol className="research-audit__trace">
            {result.trace.map((line, index) => <li key={`trace-${index}`}>{line}</li>)}
          </ol>
        </details>
      </Panel>
    </>
  )
}

export default ResearchResultPanels
